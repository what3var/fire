using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;

namespace fire.Debugging
{
    /// <summary>
    /// Running a program on an ESP32 from spark (ROADMAP 8.6, docs/NATIVE_BACKEND.md "ESP32"): the program is an ESP-IDF project (the component that `build -t esp32`
    /// writes into <c>main</c>, plus the CMakeLists.txt of the project next to it), <c>idf.py build flash</c> builds and flashes it, then spark opens the console
    /// UART itself (<see cref="SerialFramedTransport"/>): plain Run shows the console, Debug drives the debug agent of a debug build over it.
    /// </summary>
    public static class Esp32Launch
    {
        public const int DefaultBaud = 115200;

        /// <summary>The ESP-IDF folder: <paramref name="configured"/> (spark's settings), else IDF_PATH - null when neither has its export script.</summary>
        public static string? FindIdf(string? configured)
        {
            foreach (var candidate in new[] { configured, Environment.GetEnvironmentVariable("IDF_PATH") })
                if (!string.IsNullOrWhiteSpace(candidate) && File.Exists(Path.Combine(candidate, OperatingSystem.IsWindows() ? "export.bat" : "export.sh"))) return Path.GetFullPath(candidate);
            return null;
        }

        public const string MissingIdfMessage = "Running on an ESP32 needs ESP-IDF (https://docs.espressif.com/projects/esp-idf): set the environment variable IDF_PATH to its folder "
            + "(the one with export.sh / export.bat) and start spark again - or choose a target of this machine.";

        /// <summary>The name of the ESP-IDF project (CMake allows letters, digits and _).</summary>
        public static string ProjectName(string name)
        {
            string clean = Regex.Replace(name, "[^A-Za-z0-9_]", "_");
            return clean.Length == 0 || char.IsDigit(clean[0]) ? "fire_" + clean : clean;
        }

        /// <summary>Writes the CMakeLists.txt of the project in <paramref name="projectDirectory"/> (the program is its component <c>main</c>).</summary>
        public static void WriteProject(string projectDirectory, string name)
        {
            Directory.CreateDirectory(projectDirectory);
            string text = "# Generated by spark: the fire program as an ESP-IDF project (its component is main/).\ncmake_minimum_required(VERSION 3.16)\n"
                + "include($ENV{IDF_PATH}/tools/cmake/project.cmake)\n" + $"project({ProjectName(name)})\n";
            string path = Path.Combine(projectDirectory, "CMakeLists.txt");
            if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text);
        }

        /// <summary>The port to talk to: the configured one (project/target setting `port`, ESPPORT), else the only USB-serial port of the machine; null with
        /// <paramref name="why"/> when there is none or several (then esptool picks one when flashing and names it, see <see cref="SerialFramedTransport.PortFromFlashLog"/>).</summary>
        public static string? ResolvePort(string? configured, out string why)
        {
            why = "";
            if (!string.IsNullOrWhiteSpace(configured)) return configured;
            if (Environment.GetEnvironmentVariable("ESPPORT") is { Length: > 0 } env) return env;
            var ports = SerialFramedTransport.CandidatePorts();
            if (ports.Count == 1) return ports[0];
            why = ports.Count == 0 ? "no USB serial port found" : $"several serial ports ({string.Join(", ", ports)}) - set \"port\" in the project or target settings";
            return null;
        }

        /// <summary>Runs <c>idf.py [-p PORT] build flash</c> (or only build) in <paramref name="projectDirectory"/> with ESP-IDF's environment; every line of its output goes to
        /// <paramref name="log"/>. Returns whether it worked and the port esptool used.</summary>
        public static (bool Ok, string? Port) BuildAndFlash(string idfPath, string projectDirectory, string? port, bool flash, Action<string> log, CancellationToken cancel = default)
        {
            string idfArgs = (port != null ? $"-p \"{port}\" " : "") + (flash ? "build flash" : "build");
            ProcessStartInfo psi;
            if (OperatingSystem.IsWindows())
            {
                psi = new ProcessStartInfo("cmd.exe") { Arguments = $"/d /s /c \"call \"{Path.Combine(idfPath, "export.bat")}\" >nul && idf.py {idfArgs}\"" };
            }
            else
            {
                psi = new ProcessStartInfo("bash");
                psi.ArgumentList.Add("-c");
                psi.ArgumentList.Add($". \"$IDF_PATH/export.sh\" > /dev/null 2>&1 || {{ echo 'ESP-IDF: export.sh failed'; exit 1; }}; idf.py {idfArgs}");
            }
            psi.WorkingDirectory = projectDirectory;
            psi.UseShellExecute = false;
            psi.RedirectStandardOutput = true;
            psi.RedirectStandardError = true;
            psi.CreateNoWindow = true;
            psi.Environment["IDF_PATH"] = idfPath;
            var all = new StringBuilder();
            using var process = new Process { StartInfo = psi };
            void OnLine(string? line)
            {
                if (line == null) return;
                lock (all) all.AppendLine(line);
                log(line);
            }
            process.OutputDataReceived += (_, e) => OnLine(e.Data);
            process.ErrorDataReceived += (_, e) => OnLine(e.Data);
            process.Start();
            process.BeginOutputReadLine();
            process.BeginErrorReadLine();
            using (cancel.Register(() => { try { process.Kill(entireProcessTree: true); } catch (InvalidOperationException) { } }))
                process.WaitForExit();
            string text;
            lock (all) text = all.ToString();
            return (process.ExitCode == 0 && !cancel.IsCancellationRequested, port ?? SerialFramedTransport.PortFromFlashLog(text));
        }

        /// <summary>The console of a board without a debugger (plain Run): reads the port until it closes, each line to <paramref name="output"/>; frames (of a debug
        /// build that waits for a debugger) are left out.</summary>
        public static Thread Monitor(FramedDebugTransport transport, Action<string> output, Action? ended = null)
        {
            transport.Console = output;
            var thread = new Thread(() =>
            {
                while (transport.ReadMessage() != null) { }
                ended?.Invoke();
            }) { IsBackground = true, Name = "fire-esp32-monitor" };
            thread.Start();
            return thread;
        }
    }
}
