#!/bin/sh
# fire x86 package: assembles the mode switches (nasm) and writes their bytes into ../fire_x86_stubs.h
set -e
cd "$(dirname "$0")"
nasm -f bin x86_protected.asm -o /tmp/fire_x86_protected.bin
nasm -f bin x86_long.asm -o /tmp/fire_x86_long.bin
python3 - <<'PY' > ../fire_x86_stubs.h
print('/* fire x86 package: the mode switches as bytes - generated by tools/build_stubs.sh from tools/x86_protected.asm and tools/x86_long.asm (nasm); do not edit. */')
print('#ifndef FIRE_X86_STUBS_H')
print('#define FIRE_X86_STUBS_H')
for name, f in (('protected', '/tmp/fire_x86_protected.bin'), ('long', '/tmp/fire_x86_long.bin')):
    b = open(f, 'rb').read()
    print('static const unsigned char fire_x86_%sStub[%d] = {' % (name, len(b)))
    for i in range(0, len(b), 24): print('    ' + ', '.join('0x%02X' % x for x in b[i:i + 24]) + ',')
    print('};')
print('#endif')
PY
