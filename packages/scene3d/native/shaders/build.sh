#!/bin/sh
# Compiles the shaders of the hardware backend to SPIR-V (Vulkan 1.0) and writes them as C arrays into ../s3d_shaders.h.
# Needs glslangValidator (the Vulkan SDK, or the package glslang-tools). Run it after a change of a shader; the result is committed, so building fire needs no shader compiler.
set -e
cd "$(dirname "$0")"
out=../s3d_shaders.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "/* fire scene3d: the shaders of the hardware backend as SPIR-V (Vulkan 1.0). GENERATED by shaders/build.sh from the shaders in shaders/ - do not edit. */"
    echo "#ifndef FIRE_S3D_SHADERS_H"
    echo "#define FIRE_S3D_SHADERS_H"
    echo "#include <stdint.h>"
    for s in s3d_main.vert s3d_main.frag s3d_shadow.vert s3d_shadow.frag; do
        name=$(echo "$s" | sed 's/^s3d_//; s/\./_/')
        glslangValidator -V --target-env vulkan1.0 -Os -o "$tmp/$s.spv" "$s" > "$tmp/log" || { cat "$tmp/log" >&2; exit 1; }
        echo "static const uint32_t s3d_spv_$name[] = {"
        od -An -v -tx4 -w32 "$tmp/$s.spv" | sed 's/ \([0-9a-f]\{8\}\)/0x\1, /g; s/^/   /; s/, *$/,/'
        echo "};"
    done
    echo "#endif"
} > "$out"
echo "wrote $out"
