#!/bin/sh
# Compiles the shaders of the GPU backend of graphics to SPIR-V (Vulkan 1.0) and writes them as C arrays into ../fire_gfx_shaders.h.
# Needs glslangValidator (the Vulkan SDK, or the package glslang-tools). Run it after a change of a shader; the result is committed, so building fire needs no shader compiler.
set -e
cd "$(dirname "$0")"
out=../fire_gfx_shaders.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "/* fire graphics: the shaders of the GPU backend (fire_gfx_gpu.h) as SPIR-V (Vulkan 1.0). GENERATED by shaders/build.sh from the shaders in shaders/ - do not edit. */"
    echo "#ifndef FIRE_GFX_SHADERS_H"
    echo "#define FIRE_GFX_SHADERS_H"
    echo "#include <stdint.h>"
    for s in gfx_shape.vert gfx_shape.frag gfx_image.vert gfx_image.frag gfx_effect.vert gfx_effect.frag; do
        name=$(echo "$s" | sed 's/^gfx_//; s/\./_/')
        glslangValidator -V --target-env vulkan1.0 -Os -o "$tmp/$s.spv" "$s" > "$tmp/log" || { cat "$tmp/log" >&2; exit 1; }
        echo "static const uint32_t fire_gfx_spv_$name[] = {"
        od -An -v -tx4 -w32 "$tmp/$s.spv" | sed 's/ \([0-9a-f]\{8\}\)/0x\1, /g; s/^/   /; s/, *$/,/'
        echo "};"
    done
    echo "#endif"
} > "$out"
